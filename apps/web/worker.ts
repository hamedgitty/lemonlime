/**
 * Cloudflare Workers entry point. Wraps the fetch handler OpenNext generates
 * (`pnpm cf:build` writes it to .open-next/) and adds a cron handler that runs
 * the idle sweep directly, every minute (see `triggers.crons` in wrangler.jsonc).
 *
 * It also sends the phone bridge's WebSockets (/api/phone/…) to the PhoneBridge Durable
 * Object, one per computer (docs/phone-access.md). Without the PHONE_BRIDGE binding they
 * get a 503 and phone access reports itself unavailable.
 *
 * Node deployments do not use this file; they call POST /api/cron/sweep instead.
 */
// @ts-ignore: generated by `opennextjs-cloudflare build`
import openNext from "./.open-next/worker.js";
import { createWorkersContext } from "./src/lib/context.ts";
import { closeInactiveThreads, sweepRunningSandboxes } from "./src/lib/threads.ts";
import { runPluginSchedule } from "./src/lib/plugin-schedule.ts";
import { runDueAutomations } from "./src/lib/automations.ts";
import { bridgePath, type DurableObjectNamespaceLike } from "./src/lib/phone-bridge.ts";

export { PhoneBridge } from "./src/lib/phone-bridge-worker.ts";

interface ExecutionContextLike {
  waitUntil(promise: Promise<unknown>): void;
}

type FetchHandler = (request: Request, env: Record<string, unknown>, ctx: ExecutionContextLike) => Promise<Response>;

const openNextFetch = (openNext as { fetch: FetchHandler }).fetch;

export default {
  async fetch(request: Request, env: Record<string, unknown>, ctx: ExecutionContextLike): Promise<Response> {
    const path = bridgePath(new URL(request.url).pathname);
    if (path) {
      const ns = env.PHONE_BRIDGE as DurableObjectNamespaceLike | undefined;
      if (!ns || typeof ns.idFromName !== "function") return new Response("Phone access isn't set up on this server.", { status: 503 });
      if (request.headers.get("upgrade")?.toLowerCase() !== "websocket") return new Response("Expected a WebSocket", { status: 426 });
      return ns.get(ns.idFromName(path.computerId)).fetch(request);
    }
    return openNextFetch(request, env, ctx);
  },

  async scheduled(_controller: unknown, env: Record<string, unknown>, ctx: ExecutionContextLike): Promise<void> {
    ctx.waitUntil(
      (async () => {
        // Relay mode: collect runners' calls first, through the app's own route, in-process.
        if (env.LEMONLIME_RUNNER_RELAY === "true" && typeof env.LEMONLIME_PUBLIC_URL === "string" && typeof env.LEMONLIME_CRON_SECRET === "string") {
          const relayed = await (openNext as { fetch: FetchHandler })
            .fetch(
              new Request(new URL("/api/cron/relay", env.LEMONLIME_PUBLIC_URL), {
                method: "POST",
                headers: { authorization: `Bearer ${env.LEMONLIME_CRON_SECRET}` },
              }),
              env,
              ctx,
            )
            .catch(err => (console.error("[lemonlime] relay failed:", err), null));
          if (relayed && !relayed.ok) console.error(`[lemonlime] relay failed: HTTP ${relayed.status}`);
        }
        const app = createWorkersContext(env);
        const result = await sweepRunningSandboxes(app);
        if (result.paused.length || result.errors.length) {
          console.log(`[lemonlime] sweep: checked ${result.checked}, paused ${result.paused.length}, errors ${result.errors.length}`, result);
        }
        const auto = await runDueAutomations(app).catch(err => (console.error("[lemonlime] automations failed:", err), null));
        if (auto && (auto.started.length || auto.skipped.length || auto.failed.length)) console.log("[lemonlime] automations:", auto);
        const closed = await closeInactiveThreads(app).catch(err => (console.error("[lemonlime] auto-delete failed:", err), null));
        if (closed && (closed.closed.length || closed.errors.length)) console.log("[lemonlime] auto-delete:", closed);
        await runPluginSchedule(app);
      })().catch(err => {
        // A rejected waitUntil promise is dropped without a trace; say why the sweep didn't run.
        console.error("[lemonlime] sweep failed:", err);
      }),
    );
  },
};
