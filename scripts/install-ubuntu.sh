#!/usr/bin/env bash
# Install a self-hosted LemonLime on a fresh Ubuntu 24.04 server.
#
#   curl -fsSL https://raw.githubusercontent.com/hamedgitty/lemonlime/main/scripts/install-ubuntu.sh -o install.sh
#   less install.sh                     # read it first
#   sudo bash install.sh lemonlime.example.com you@example.com
#
# Arguments: the domain that points at this server (for HTTPS), and the email address
# sign-in codes come from. Leave the domain out to serve plain HTTP on port 80 (only on
# a private network). Installs Docker, puts LemonLime in /opt/lemonlime, writes
# /opt/lemonlime/.env with freshly generated secrets, builds the images and starts it.
# Running it again updates the code and keeps your .env and data.
set -euo pipefail

DOMAIN="${1:-}"
EMAIL_FROM="${2:-}"
DIR="${LEMONLIME_DIR:-/opt/lemonlime}"
REPO="${LEMONLIME_REPO:-https://github.com/hamedgitty/lemonlime.git}"
BRANCH="${LEMONLIME_BRANCH:-main}"

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
die() { printf 'install-ubuntu: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "run as root (sudo bash install.sh ...)"
. /etc/os-release
[ "${ID:-}" = "ubuntu" ] || die "this script is for Ubuntu (found ${ID:-unknown})"
case "${VERSION_ID:-}" in 24.04|24.10|25.04|25.10) ;; *) echo "Warning: tested on Ubuntu 24.04, found ${VERSION_ID:-unknown}." ;; esac

say "Installing Docker and git"
apt-get update -q
apt-get install -y -q ca-certificates curl git openssl docker.io docker-compose-v2 docker-buildx
systemctl enable --now docker

say "Getting LemonLime into $DIR"
if [ -d "$DIR/.git" ]; then
  git -C "$DIR" fetch -q origin "$BRANCH"
  git -C "$DIR" checkout -q "$BRANCH"
  git -C "$DIR" reset -q --hard "origin/$BRANCH"
else
  git clone -q --branch "$BRANCH" "$REPO" "$DIR"
fi
cd "$DIR"

if [ -f .env ]; then
  say "Keeping the existing $DIR/.env"
else
  say "Writing $DIR/.env with new secrets"
  if [ -n "$DOMAIN" ]; then PUBLIC_URL="https://$DOMAIN"; SITE="$DOMAIN"; else PUBLIC_URL="http://$(hostname -I | awk '{print $1}')"; SITE=":80"; fi
  umask 077
  cat > .env <<ENV
# Generated by scripts/install-ubuntu.sh. Keep this file private.
LEMONLIME_PUBLIC_URL=$PUBLIC_URL
LEMONLIME_SITE_ADDRESS=$SITE
BETTER_AUTH_SECRET=$(openssl rand -base64 32)
LEMONLIME_TOKEN_SECRET=$(openssl rand -hex 32)
LEMONLIME_CRON_SECRET=$(openssl rand -hex 32)
LEMONLIME_EMAIL_FROM=LemonLime <${EMAIL_FROM:-sign-in@${DOMAIN:-example.com}}>
# Sign-in codes are emailed with Resend: add your key (https://resend.com), then run
# "docker compose up -d" in $DIR again.
RESEND_API_KEY=
ENV
fi

say "Building images (this takes a few minutes the first time)"
docker compose --profile build build

say "Starting LemonLime"
docker compose up -d

URL=$(grep '^LEMONLIME_PUBLIC_URL=' .env | cut -d= -f2-)
say "LemonLime is running at $URL"
if ! grep -q '^RESEND_API_KEY=.\+' .env; then
  echo "Next: add RESEND_API_KEY to $DIR/.env so sign-in codes can be emailed, then run:"
  echo "  cd $DIR && docker compose up -d"
fi
if [ -n "$DOMAIN" ]; then
  echo "Make sure $DOMAIN points at this server and ports 80 and 443 are open; HTTPS is set up automatically."
fi
echo "Logs: cd $DIR && docker compose logs -f web"
