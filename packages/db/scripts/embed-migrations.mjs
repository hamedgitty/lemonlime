// Embeds migrations/*.sql into src/migrations.ts so bundled apps (Next.js) and
// tests can apply them without reading files at runtime.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "migrations");
const files = readdirSync(dir).filter(f => f.endsWith(".sql")).sort();
const entries = files.map(f => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))} },`);
const out = `// Generated by scripts/embed-migrations.mjs from migrations/*.sql. Do not edit.

export interface Migration {
  /** File name in migrations/, as recorded in the d1_migrations table. */
  name: string;
  sql: string;
}

export const migrations: readonly Migration[] = [
${entries.join("\n")}
];
`;
writeFileSync(join(root, "src", "migrations.ts"), out);
console.log(`Embedded ${files.length} migration(s).`);
